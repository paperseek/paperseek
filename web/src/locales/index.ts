const STORAGE_KEY = "paperseek.locale";

function initialLanguage(): Language {
  try {
    const stored = globalThis.localStorage?.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "zh") return stored;
  } catch {
    // Preference storage is unavailable; fall through to the browser default.
  }
  return globalThis.navigator?.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

const locale = reactive({ language: initialLanguage() as Language });

function applyDocumentLanguage(language: Language): void {
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
}

// Applied at module load, before the app mounts, to avoid a language flash (§10.11).
applyDocumentLanguage(locale.language);

/** Add product-specific text (such as a deployment's own error codes) before the app mounts. */
export function extendMessages(entries: Record<Language, Record<string, string>>): void {
  for (const language of Object.keys(entries) as Language[]) Object.assign(messages[language], entries[language]);
}

export function useLocale() {
  const t = (key: string): string => messages[locale.language][key] || (reviewMessages[locale.language] as Record<string, string>)[key] || key;
  const displayName = (prefix: "provider" | "source", value: string, fallback = ""): string => {
    const key = `${prefix}_${value || "off"}`;
    const localized = t(key);
    return localized === key ? (fallback || value) : localized;
  };
  const providerName = (value: string): string => displayName("provider", value);
  const sourceName = (value: string, fallback = ""): string => displayName("source", value, fallback);
  const filterOptionName = (source: string, value: string, fallback: string): string => {
    if (locale.language === "zh" && source === "openalex") return openAlexFieldNamesZh[value] || fallback;
    return fallback;
  };
  const filterDomainName = (source: string, value: string): string => {
    if (locale.language === "zh" && source === "openalex") return openAlexDomainNamesZh[value] || value;
    return value;
  };
  const runMessage = (value: string, kind: "warning" | "error" = "warning"): string => {
    const exact = t(value);
    if (exact !== value) return exact;
    const code = value.toLowerCase();
    if (code.startsWith("query_")) return t("runWarningQuery");
    if (code.startsWith("citation_")) return t("runWarningCitation");
    if (code.startsWith("ranking_")) return t("runWarningRanking");
    if (code.startsWith("retrieval_")) return t("runWarningRetrieval");
    return t(kind === "error" ? "runErrorGeneric" : "runWarningGeneric");
  };
  const setLanguage = (language: Language) => {
    locale.language = language;
    applyDocumentLanguage(language);
    try {
      globalThis.localStorage?.setItem(STORAGE_KEY, language);
    } catch {
      // Preference persistence is best-effort and never blocks the UI.
    }
  };
  return {
    filterDomainName,
    filterOptionName,
    language: computed(() => locale.language),
    providerName,
    runMessage,
    setLanguage,
    sourceName,
    t,
  };
}
