export type UiKey = keyof typeof zh;

export function useUi() {
  const { language } = useLocale();
  return (key: UiKey, values: Record<string, string | number> = {}): string =>
    (language.value === "zh" ? zh : en)[key].replace(/\{(\w+)\}/g, (_, name: string) =>
      String(values[name] ?? `{${name}}`));
}

/** Readable failure text for a probe or API error code. */
export function useUiError() {
  const u = useUi();
  return (code: string): string => {
    const key = `err_${code}` as UiKey;
    if (key in zh) return u(key);
    const http = /^http_(\d+)$/.exec(code);
    return http ? `HTTP ${http[1]}` : u("err_generic");
  };
}
